# --- АВТООПРЕДЕЛЕНИЕ IP БАЗЫ ДАННЫХ В DOCKER ---
def get_docker_db_ip(container_name="zabbix-db"):
    """
    Автоматически находит IP-адрес Docker-контейнера с базой данных.
    Если контейнер не найден или Docker недоступен, возвращает localhost.
    """
    try:
        # Вызываем docker inspect для получения IP-адреса контейнера
        cmd = ["docker", "inspect", "-f", "{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}", container_name]
        result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=True)
        ip = result.stdout.strip()
        if ip:
            return ip
    except Exception as e:
        print(f"[WARNING] Не удалось определить IP Docker-контейнера '{container_name}': {e}")
    
    # Резервный вариант, если скрипт запущен в одной сети или через порты наружу
    return "127.0.0.1" 


